import type { LoanKind } from "./LoanKind";

export interface Loan {
    id: string;

    // Bank account used for EMI payments (chosen in the loan form).
    accountId: string | null;

    // 1:1 liability account (account_type = LOAN) that represents this loan in
    // the unified Accounts list. Managed by LoanService, never edited via the
    // form. Analogous to investments.account_id / the Investment ↔ Account link.
    loanAccountId: string | null;

    lenderInstitutionId: string | null;

    // The user's own free-text description (e.g. "Home Loan"). Drives no
    // behaviour - see loanKind.
    loanType: string;

    /**
     * The Loan Type that decides how the loan works (migration 047):
     * TERM_LOAN or OVERDRAFT. Always present on rows read from the
     * database; optional for hand-built objects, where absent means
     * TERM_LOAN (see isOverdraft).
     */
    loanKind?: LoanKind;

    /** OVERDRAFT only: the OD limit. null for a Term Loan. */
    creditLimit?: number | null;

    /** OVERDRAFT only: the amount used as on openingUsedAsOf. */
    openingUsed?: number | null;

    /** OVERDRAFT only: linked transactions after this date move the used amount. */
    openingUsedAsOf?: string | null;

    /**
     * OVERDRAFT only: every bank account linked to the OD
     * (overdraft_accounts, migration 048) - all of them feed one position.
     * Empty for a Term Loan, whose payment account is accountId.
     */
    linkedAccountIds?: string[];

    name: string;

    /**
     * The lender's own account number for the loan (migration 050) -
     * always text, so leading zeros and letters survive. null when not
     * entered; optional for hand-built objects.
     */
    loanAccountNumber?: string | null;

    principalAmount: number;

    interestRate: number;

    interestType: "REDUCING" | "FLAT";

    tenureMonths: number | null;

    emiAmount: number | null;

    /**
     * Optional irregular first instalment: the broken-period (pre-EMI)
     * interest collected as instalment 1 before the regular EMIs start.
     * Interest only; followed by `tenureMonths` regular EMIs of
     * `emiAmount`. null/undefined = every instalment is the regular EMI.
     */
    firstInstallmentAmount?: number | null;

    startDate: string;

    maturityDate: string | null;

    outstandingPrincipal: number;

    outstandingInterest: number;

    // Paid instalments, as READ: derived from the EMI schedule (its PAID
    // rows - linked payments and "Settled before FinWea" alike; see
    // LoanRepository PAID_INSTALMENTS_SQL). Never typed in or edited.
    paidInstallments: number;

    currencyId: string;

    status: "ACTIVE" | "CLOSED" | "ON_HOLD" | "DEFAULTED";

    notes?: string;

    // ---- Add Loan setup (migration 051). All optional: an older loan has
    // none of them (NULL = "not recorded"), and nothing derives a value for
    // it. See loans/setup/.

    loanPurpose?: string | null;

    rateType?: "FIXED" | "FLOATING" | null;

    /** MONTHLY_RATE (rate / 12) or ACTUAL_365 (actual days / 365). */
    interestCalculationMethod?: "MONTHLY_RATE" | "ACTUAL_365" | null;

    sanctionDate?: string | null;

    sanctionedAmount?: number | null;

    /** The lender's actual first EMI due date. */
    firstEmiDate?: string | null;

    repaymentFrequency?: "MONTHLY" | null;

    paymentDay?: number | null;

    gracePeriodMonths?: number | null;

    balloonAmount?: number | null;

    /** GENERATED by FinWea, or the lender's LENDER_CSV. NULL: older loan. */
    scheduleSource?: "GENERATED" | "LENDER_CSV" | null;

    /** OVERDRAFT only: caps the available amount below the limit. */
    drawingPower?: number | null;

    createdAt: string;

    updatedAt: string;
}
