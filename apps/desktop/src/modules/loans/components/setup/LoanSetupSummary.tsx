import { useEffect, useState } from "react";

import type { Loan } from "../../types";
import {
    LoanSetupRepository,
    type StoredDisbursement,
    type StoredInitialExpense,
} from "../../repositories/LoanSetupRepository";
import { formatMoney } from "../../setup/loanSetupAccounting";
import { EXPENSE_SETTLEMENT_LABELS, INITIAL_EXPENSE_TYPE_LABELS } from "../../setup/loanSetupTypes";
import { StepSection, formatDisplayDate } from "./setupFields";

/**
 * The Add Loan setup saved with a loan (migration 051), read-only:
 * lender terms, disbursements and initial expenses. Renders nothing for a
 * loan created before the setup workflow - there is nothing to show and
 * nothing is derived for it.
 */
export function LoanSetupSummary({ loan }: { loan: Loan }) {
    const [disbursements, setDisbursements] = useState<StoredDisbursement[]>([]);
    const [expenses, setExpenses] = useState<StoredInitialExpense[]>([]);

    useEffect(() => {
        let mounted = true;
        const repository = new LoanSetupRepository();

        Promise.all([repository.getDisbursements(loan.id), repository.getInitialExpenses(loan.id)])
            .then(([d, e]) => {
                if (mounted) {
                    setDisbursements(d);
                    setExpenses(e);
                }
            })
            .catch(error => console.error("Failed to load loan setup:", error));

        return () => {
            mounted = false;
        };
    }, [loan.id]);

    const terms: Array<[string, string]> = [];
    const add = (label: string, value: string | null | undefined) => {
        if (value) terms.push([label, value]);
    };

    add("Loan Purpose", loan.loanPurpose);
    add("Rate", loan.rateType === "FLOATING" ? "Floating" : loan.rateType === "FIXED" ? "Fixed" : null);
    add(
        "Interest Method",
        loan.interestCalculationMethod === "ACTUAL_365"
            ? "Actual days / 365"
            : loan.interestCalculationMethod === "MONTHLY_RATE"
              ? "Monthly rate (rate ÷ 12)"
              : null
    );
    add("Sanction Date", loan.sanctionDate ? formatDisplayDate(loan.sanctionDate) : null);
    add("Sanctioned Amount", loan.sanctionedAmount ? formatMoney(loan.sanctionedAmount) : null);
    add("First EMI Date", loan.firstEmiDate ? formatDisplayDate(loan.firstEmiDate) : null);
    add("Payment Day", loan.paymentDay ? String(loan.paymentDay) : null);
    add("Grace Period", loan.gracePeriodMonths ? `${loan.gracePeriodMonths} months` : null);
    add("Balloon Payment", loan.balloonAmount ? formatMoney(loan.balloonAmount) : null);
    add("Schedule", loan.scheduleSource === "LENDER_CSV" ? "Lender's official schedule (CSV)" : loan.scheduleSource === "GENERATED" ? "Generated by FinWea" : null);
    add("Drawing Power", loan.drawingPower !== null && loan.drawingPower !== undefined ? formatMoney(loan.drawingPower) : null);

    if (terms.length === 0 && disbursements.length === 0 && expenses.length === 0) {
        return null;
    }

    const gross = disbursements.reduce((sum, d) => sum + d.grossAmount, 0);
    const net = disbursements.reduce((sum, d) => sum + d.netAmount, 0);
    const expenseTotal = expenses.reduce((sum, e) => sum + e.totalAmount, 0);

    return (
        <>
            {terms.length > 0 && (
                <StepSection variant="plain" title="Lender Terms">
                    <div className="grid grid-cols-2 gap-x-8 gap-y-4">
                        {terms.map(([label, value]) => (
                            <div key={label} className="min-w-0 space-y-1">
                                <div className="text-[11px] font-semibold uppercase tracking-[0.06em] text-slate-400">{label}</div>
                                <div className="break-words text-sm text-slate-800">{value}</div>
                            </div>
                        ))}
                    </div>
                </StepSection>
            )}

            {disbursements.length > 0 && (
                <StepSection variant="plain" title={`Disbursements - gross ${formatMoney(gross)}, net ${formatMoney(net)}`}>
                    <table className="w-full text-xs">
                        <thead className="text-slate-400">
                            <tr>
                                {["#", "Date", "Gross", "Deductions", "Net", "Account", "Bank credit"].map(h => (
                                    <th key={h} className="px-2 py-1 text-left font-medium">{h}</th>
                                ))}
                            </tr>
                        </thead>
                        <tbody>
                            {disbursements.map(d => (
                                <tr key={d.id} className="border-t border-slate-100">
                                    <td className="px-2 py-1">{d.sequence}</td>
                                    <td className="px-2 py-1">{formatDisplayDate(d.disbursementDate)}</td>
                                    <td className="px-2 py-1">{formatMoney(d.grossAmount)}</td>
                                    <td className="px-2 py-1">{formatMoney(d.deductionsAmount)}</td>
                                    <td className="px-2 py-1">{formatMoney(d.netAmount)}</td>
                                    <td className="px-2 py-1">{d.destinationAccountName ?? "-"}</td>
                                    <td className="px-2 py-1">{d.transactionId ? "Linked" : "Not linked"}</td>
                                </tr>
                            ))}
                        </tbody>
                    </table>
                </StepSection>
            )}

            {expenses.length > 0 && (
                <StepSection variant="plain" title={`Initial Expenses - ${formatMoney(expenseTotal)}`}>
                    <table className="w-full text-xs">
                        <thead className="text-slate-400">
                            <tr>
                                {["Type", "Date", "Base", "GST", "Total", "Settlement", "Bank debit"].map(h => (
                                    <th key={h} className="px-2 py-1 text-left font-medium">{h}</th>
                                ))}
                            </tr>
                        </thead>
                        <tbody>
                            {expenses.map(e => (
                                <tr key={e.id} className="border-t border-slate-100">
                                    <td className="px-2 py-1">{INITIAL_EXPENSE_TYPE_LABELS[e.expenseType] ?? e.expenseType}{e.description ? ` - ${e.description}` : ""}</td>
                                    <td className="px-2 py-1">{formatDisplayDate(e.expenseDate)}</td>
                                    <td className="px-2 py-1">{formatMoney(e.baseAmount)}</td>
                                    <td className="px-2 py-1">{formatMoney(e.gstAmount)}{e.gstRate !== null ? ` (${e.gstRate}%)` : ""}</td>
                                    <td className="px-2 py-1">{formatMoney(e.totalAmount)}</td>
                                    <td className="px-2 py-1">{EXPENSE_SETTLEMENT_LABELS[e.settlement] ?? e.settlement}</td>
                                    <td className="px-2 py-1">
                                        {e.settlement !== "PAID_SEPARATELY" ? "None (no bank debit)" : e.transactionId ? "Linked" : "Not linked"}
                                    </td>
                                </tr>
                            ))}
                        </tbody>
                    </table>
                </StepSection>
            )}
        </>
    );
}
